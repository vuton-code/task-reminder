import pytest
from playwright.sync_api import sync_playwright, expect
pytestmark=pytest.mark.django_db(transaction=True)

@pytest.mark.parametrize("engine", ["chromium", "firefox", "webkit"])
def test_autofill_password_visibility_and_error_timing(live_server,engine):
    with sync_playwright() as pw:
        browser=getattr(pw,engine).launch()
        page=browser.new_page(viewport={"width":390,"height":844})
        page.goto(live_server.url+"/accounts/register")
        expect(page).to_have_title("Create your account | Projects Management Hub")
        username=page.get_by_label("Username")
        email=page.get_by_label("Email")
        password=page.get_by_label("Password")
        expect(username).to_have_attribute("autocomplete","username")
        expect(password).to_have_attribute("autocomplete","new-password")
        expect(email).to_have_attribute("aria-invalid","false")
        username.fill("newperson"); email.fill("invalid")
        page.get_by_role("button",name="Create account",exact=True).click()
        expect(email).to_have_attribute("aria-invalid","true")
        expect(page.locator("#id_email-client-error")).to_be_visible()
        email.fill("new@example.test")
        expect(email).to_have_attribute("aria-invalid","false")
        expect(page.locator("#id_email-client-error")).to_be_hidden()
        password.fill("a-long-test-password")
        toggle=page.get_by_role("button",name="Show password",exact=True)
        toggle.click()
        expect(password).to_have_attribute("type","text")
        expect(toggle).to_have_attribute("aria-pressed","true")
        toggle.click()
        expect(password).to_have_attribute("type","password")
        page.get_by_label("Confirmation").fill("mismatched-password")
        page.get_by_role("button",name="Create account",exact=True).click()
        expect(page.get_by_label("Confirmation")).to_have_attribute("aria-invalid","true")
        expect(page.get_by_text("Passwords must match.",exact=True)).to_be_visible()
        assert page.evaluate("document.documentElement.scrollWidth <= innerWidth")
        browser.close()
